// Embeds drizzle/ SQL migrations into src/db/migrations.ts so the app and
// tests run the same versioned migrations without runtime file access.
// Run after `npx drizzle-kit generate`: npm run db:embed
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const drizzleDir = new URL("../drizzle", import.meta.url).pathname;
const outFile = new URL("../src/db/migrations.ts", import.meta.url).pathname;

const files = readdirSync(drizzleDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const migrations = files.map((file) => {
  const raw = readFileSync(join(drizzleDir, file), "utf8");
  // drizzle-kit brackets migrations with PRAGMA foreign_keys toggles; the
  // runner manages FK enforcement itself and pragmas are no-ops inside
  // transactions, so strip them.
  const statements = raw
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && !/^PRAGMA foreign_keys/i.test(s));
  return { id: file.replace(/\.sql$/, ""), statements };
});

const banner = `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit.
// Source: drizzle/*.sql (drizzle-kit generate)

export interface EmbeddedMigration {
  id: string;
  statements: string[];
}

export const migrations: EmbeddedMigration[] = `;

const body = JSON.stringify(migrations, null, 2)
  .replace(/"([a-zA-Z_]+)":/g, "$1:")
  .replace(/"id":/g, "id:")
  .replace(/"statements":/g, "statements:");

writeFileSync(outFile, `${banner}${body};\n`, "utf8");
console.log(`Embedded ${migrations.length} migration(s) -> ${outFile}`);
